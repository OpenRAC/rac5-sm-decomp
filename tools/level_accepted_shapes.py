#!/usr/bin/env python3
"""Count accepted level bodies by relocation-masked shape, like the level denominator.

The level denominator (config/levels/shape_scenario_summary.json) counts every
relocation-masked candidate shape once, at its largest multiplicity in one of the
20 retained modules. Counting accepted bodies by source instead credits the
address-variant copies of one function (one source per level) up to 20 times
against a denominator that counts them once. This tool counts the accepted
placements of config/levels/bodies.tsv by the denominator's rule: each accepted
placement in a retained module is rehashed against the pinned disc with the same
relocation mask, and every (size, masked shape) is credited once per module at its
largest accepted multiplicity. Shape units are candidate functions, not a reviewed
function catalogue.

The same pass writes config/levels/shape_units.tsv, the public per-shape map
behind the progress report. Each row is one relocation-masked candidate shape:
its bytes and candidate functions at its largest per-module multiplicity, and
the part of them that accepted C reproduces. A candidate unit counts as matched
when one accepted placement of its own module covers all of its bytes (an
accepted body whose bounds differ from the inventory covers whole candidate
units, never part of one), at the shape's largest covered multiplicity in one
module. One more row per module holds its code outside every candidate unit and
the accepted bytes inside it. A shape found in several modules sits in
src/levels/shared/, any other in its module's directory, as the sources do.
The table's totals equal the level denominator.

The private --write pass needs the pinned disc and the private candidate
worklists; --check verifies that the committed summary and table belong to the
current tables and stay within the denominator.
"""

from __future__ import annotations

import argparse
import bisect
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path

from disc import IsoDisc, verify_disc
from level_function_inventory import masked_body, relocations
from level_ghidra_crosscheck import rows
from level_source_layout import MODULE_DIRS, SHARED, SOURCE_DIRS

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "config/levels/accepted_shape_summary.json"
UNITS = ROOT / "config/levels/shape_units.tsv"
BODIES = ROOT / "config/levels/bodies.tsv"
SHAPE = ROOT / "config/levels/shape_scenario_summary.json"
INVENTORY = ROOT / "config/levels/function_inventory_summary.json"
MODULES = ROOT / "config/levels/modules.tsv"
CODE = ROOT / "config/levels/code_intervals.tsv"
TARGET = ROOT / "config/target.json"
UNITS_HEADER = ["home", "name", "bytes", "matched_bytes", "functions",
                "matched_functions", "modules", "source"]
UNITS_NOTE = ("# Generated by tools/level_accepted_shapes.py --write: one row per "
              "relocation-masked candidate shape at its largest per-module multiplicity, "
              "one row per module for code outside candidate units. Candidate functions, "
              "not a reviewed function catalogue.")
UNBOUNDED = "code_without_function_bounds"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def retained_modules() -> tuple[set[str], set[str]]:
    """The 20 modules the shape scenario measures, and the identical copies it leaves out."""
    inventory = json.loads(INVENTORY.read_text(encoding="utf-8"))
    code = {row["module"] for row in rows(CODE)}
    copies = {module for group in inventory["identical_full_interval_groups"]
              for module in group[1:]}
    retained = code - copies
    if len(code) != 21 or len(retained) != 20:
        raise ValueError("pinned module catalogue changed")
    return retained, copies


def accepted_placements() -> list[tuple[str, int, int]]:
    out = []
    for row in rows(BODIES):
        out.append((row["module"], int(row["offset"], 0), int(row["size"], 0)))
    return out


def accepted_counts(keys: list[tuple[str, int, str]]) -> dict[str, int]:
    """keys: (module, size, masked shape) of accepted placements in retained modules."""
    shapes: dict[tuple[int, str], Counter[str]] = defaultdict(Counter)
    for module, size, masked in keys:
        if size <= 0 or not masked:
            raise ValueError("accepted placement is missing bytes or a fingerprint")
        shapes[size, masked][module] += 1
    return {
        "accepted_masked_shape_groups": len(shapes),
        "accepted_masked_max_per_module_bytes": sum(
            size * max(counts.values()) for (size, _hash), counts in shapes.items()),
        "accepted_masked_max_per_module_units": sum(
            max(counts.values()) for counts in shapes.values()),
    }


def accepted_spans() -> dict[str, list[tuple[int, int, str]]]:
    """Accepted C placements per module as sorted (start, end, source) spans."""
    spans: dict[str, list[tuple[int, int, str]]] = defaultdict(list)
    for row in rows(BODIES):
        start = int(row["offset"], 0)
        spans[row["module"]].append((start, start + int(row["size"], 0), row["source"]))
    for module, items in spans.items():
        items.sort()
        if any(end > nxt for (_s, end, _src), (nxt, _e, _n) in zip(items, items[1:])):
            raise ValueError(f"{module}: accepted placements overlap")
    return spans


def shape_unit_rows(records: list[tuple[str, int, int, str]],
                    spans: dict[str, list[tuple[int, int, str]]],
                    interval_bytes: dict[str, int], order: list[str]) -> list[dict[str, object]]:
    """Map rows from candidate units and accepted placements.

    records: (module, offset, size, masked shape) of the candidate units of the
    retained modules; spans: accepted_spans(); interval_bytes: the retained
    candidate interval bytes per module; order: retained modules in report order.
    """
    starts = {module: [start for start, _end, _source in items] for module, items in spans.items()}

    def cover(module: str, offset: int, size: int) -> str | None:
        index = bisect.bisect_right(starts.get(module, []), offset + size - 1) - 1
        if index < 0:
            return None
        start, end, source = spans[module][index]
        if start <= offset and offset + size <= end:
            return source
        if end > offset:
            raise ValueError(f"{module}:{offset:06X}: accepted C covers part of a candidate unit")
        return None

    rank = {module: number for number, module in enumerate(order)}
    groups: dict[tuple[int, str], dict[str, list[tuple[int, str | None]]]] = defaultdict(
        lambda: defaultdict(list))
    unit_bytes: Counter[str] = Counter()
    covered_bytes: Counter[str] = Counter()
    for module, offset, size, masked in records:
        source = cover(module, offset, size)
        groups[size, masked][module].append((offset, source))
        unit_bytes[module] += size
        if source:
            covered_bytes[module] += size
    out: list[tuple[tuple[int, int, int], dict[str, object]]] = []
    homes = {directory: number for number, directory in
             enumerate([MODULE_DIRS[module] for module in order] + [SHARED])}
    for (size, _masked), by_module in groups.items():
        count = max(len(items) for items in by_module.values())
        matched = max(sum(1 for _offset, source in items if source)
                      for items in by_module.values())
        placed = sorted((rank[module], offset, module, source)
                        for module, items in by_module.items() for offset, source in items)
        _rank, offset, module, source = next((item for item in placed if item[3]), placed[0])
        home = SHARED if len(by_module) > 1 else MODULE_DIRS[module]
        out.append(((homes[home], rank[module], offset), {
            "home": home, "name": f"{module.removesuffix('.REL')}_{offset:06X}",
            "bytes": size * count, "matched_bytes": size * matched,
            "functions": count, "matched_functions": matched,
            "modules": len(by_module), "source": source or ""}))
    for module in order:
        accepted = sum(end - start for start, end, _source in spans.get(module, []))
        outside = interval_bytes[module] - unit_bytes[module]
        inside = accepted - covered_bytes[module]
        if outside < 0 or not 0 <= inside <= outside:
            raise ValueError(f"{module}: accepted C escapes the candidate code intervals")
        if outside:
            home = MODULE_DIRS[module]
            out.append(((homes[home], len(order), 0), {
                "home": home, "name": UNBOUNDED, "bytes": outside, "matched_bytes": inside,
                "functions": 0, "matched_functions": 0, "modules": 1, "source": ""}))
    out.sort(key=lambda item: item[0])
    return [row for _key, row in out]


def units_text(table: list[dict[str, object]]) -> str:
    lines = [UNITS_NOTE, "\t".join(UNITS_HEADER)]
    lines.extend("\t".join(str(row[field]) for field in UNITS_HEADER) for row in table)
    return "\n".join(lines) + "\n"


def read_units(path: Path = UNITS) -> list[dict[str, object]]:
    """The committed map rows, with their numeric fields as integers."""
    table = []
    for row in rows(path):
        table.append({field: (int(row[field]) if field in ("bytes", "matched_bytes", "functions",
                                                            "matched_functions", "modules")
                              else row[field]) for field in UNITS_HEADER})
    return table


def map_totals(table: list[dict[str, object]]) -> dict[str, int]:
    return {"map_rows": len(table),
            "map_bytes": sum(row["bytes"] for row in table),
            "map_matched_bytes": sum(row["matched_bytes"] for row in table),
            "map_functions": sum(row["functions"] for row in table),
            "map_matched_functions": sum(row["matched_functions"] for row in table),
            "map_matched_outside_units_bytes": sum(
                row["matched_bytes"] for row in table if row["name"] == UNBOUNDED)}


def measure(image: Path) -> tuple[dict[str, object], str]:
    import level_shape_scenario  # private worklists, read only by the write pass

    retained, copies = retained_modules()
    target = json.loads(TARGET.read_text(encoding="utf-8"))
    modules = {Path(row["path"]).name: row for row in rows(MODULES)}
    code = {row["module"]: row for row in rows(CODE)}
    placements = accepted_placements()
    by_module: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for module, offset, size in placements:
        if module not in code:
            raise ValueError(f"accepted placement names an unknown module: {module}")
        by_module[module].append((offset, size))
    records, _retained_bytes, _residual = level_shape_scenario.measured_unit_records(image)
    units = [(module, size, raw, masked) for module, _offset, size, raw, masked in records]
    unit_keys = {(size, masked) for _module, size, _raw, masked in units}
    keys: list[tuple[str, int, str]] = []
    with IsoDisc(image) as disc:
        verify_disc(disc, target)
        for module in sorted(retained):
            data = disc.file_bytes("LVL/" + module)
            if hashlib.sha256(data).hexdigest() != modules[module]["sha256"]:
                raise ValueError(f"{module} differs from pinned module")
            start = int(code[module]["start"], 16)
            code_end = int(code[module]["end_exclusive"], 16)
            indexed, _pointers = relocations(data, code_end)
            sites = sorted(indexed)
            for offset, size in sorted(by_module.get(module, [])):
                if not start <= offset < offset + size <= code_end:
                    raise ValueError(f"{module} accepted placement escapes candidate code")
                masked, _count = masked_body(data[offset:offset + size], offset, indexed, sites)
                keys.append((module, size, masked))
    counts = accepted_counts(keys)
    outside = {(size, masked) for _module, size, masked in keys} - unit_keys
    candidate: dict[tuple[int, str], Counter[str]] = defaultdict(Counter)
    for module, size, _raw, masked in units:
        candidate[size, masked][module] += 1
    order = [module for module in MODULE_DIRS if module in retained]
    table = shape_unit_rows(
        [(module, offset, size, masked) for module, offset, size, _raw, masked in records],
        accepted_spans(), {module: int(code[module]["interval_bytes"]) for module in order},
        order)
    text = units_text(table)
    return {
        "status": "accepted_bodies_by_masked_shape",
        "module_count": 20,
        "bodies_table_sha256": digest(BODIES),
        "shape_summary_sha256": digest(SHAPE),
        "retained_placements": len(keys),
        "identical_module_copy_placements": sum(len(by_module.get(m, [])) for m in copies),
        "accepted_placements_by_module": {
            module: len(by_module.get(module, [])) for module in sorted(retained)},
        "candidate_body_units": len(units),
        "candidate_units_by_module": dict(sorted(
            Counter(module for module, _size, _raw, _masked in units).items())),
        "candidate_masked_max_per_module_bytes": sum(
            size * max(c.values()) for (size, _hash), c in candidate.items()),
        "candidate_masked_max_per_module_units": sum(
            max(c.values()) for c in candidate.values()),
        **counts,
        "accepted_shapes_outside_candidate_units": len(outside),
        "accepted_shape_bytes_outside_candidate_units": sum(size for size, _hash in outside),
        "shape_units_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        **map_totals(table),
        "warning": ("Accepted bodies are credited once per relocation-masked shape, at "
                    "their largest per-module multiplicity, like the optimistic level "
                    "denominator; shape units are candidate functions, not a reviewed "
                    "function catalogue."),
    }, text


def check_summary(summary: dict[str, object]) -> None:
    shape = json.loads(SHAPE.read_text(encoding="utf-8"))
    retained, copies = retained_modules()
    placements = accepted_placements()
    per_module = Counter(module for module, _offset, _size in placements)
    if (summary.get("status") != "accepted_bodies_by_masked_shape"
            or summary.get("module_count") != 20
            or summary.get("bodies_table_sha256") != digest(BODIES)
            or summary.get("shape_summary_sha256") != digest(SHAPE)
            or summary["accepted_placements_by_module"] !=
            {module: per_module.get(module, 0) for module in sorted(retained)}
            or summary["retained_placements"] != sum(per_module[m] for m in retained)
            or summary["identical_module_copy_placements"] != sum(per_module[m] for m in copies)
            or summary["retained_placements"] + summary["identical_module_copy_placements"]
            != len(placements)
            or not (0 <= summary["accepted_masked_shape_groups"] <=
                    summary["accepted_masked_max_per_module_units"] <=
                    summary["retained_placements"])
            or summary["candidate_body_units"] != shape["body_units"]
            or sum(summary["candidate_units_by_module"].values()) != shape["body_units"]
            or sorted(summary["candidate_units_by_module"]) != sorted(retained)
            or summary["candidate_masked_max_per_module_bytes"] !=
            shape["masked_max_per_module_bytes"]
            or not (shape["masked_shape_groups"] <=
                    summary["candidate_masked_max_per_module_units"] <=
                    shape["body_units"])
            or summary["accepted_masked_max_per_module_units"] >
            summary["candidate_masked_max_per_module_units"]
            or not (0 <= summary["accepted_masked_max_per_module_bytes"] <=
                    shape["masked_max_per_module_scenario_bytes"])
            or any(summary["accepted_placements_by_module"][module] >
                   summary["candidate_units_by_module"][module] for module in sorted(retained))
            or summary["accepted_shapes_outside_candidate_units"] >
            summary["accepted_masked_shape_groups"]):
        raise ValueError("accepted shape summary is stale or exceeds the denominator")
    check_units(summary, shape)


def check_units(summary: dict[str, object], shape: dict[str, object]) -> None:
    """The committed map table belongs to this summary and closes on the denominator."""
    if digest(UNITS) != summary.get("shape_units_sha256"):
        raise ValueError("shape unit table is stale")
    table = read_units()
    sources = {row["source"] for row in rows(BODIES)}
    names = [(row["home"], row["name"]) for row in table]
    if (map_totals(table) != {key: summary.get(key) for key in map_totals(table)}
            or summary["map_bytes"] != shape["masked_max_per_module_scenario_bytes"]
            or summary["map_functions"] != summary["candidate_masked_max_per_module_units"]
            or len(set(names)) != len(names)
            or any(row["home"] not in SOURCE_DIRS
                   or not 0 <= row["matched_bytes"] <= row["bytes"]
                   or not 0 <= row["matched_functions"] <= row["functions"]
                   or (row["source"] and row["source"] not in sources)
                   or (row["name"] != UNBOUNDED
                       and (row["functions"] < 1 or row["bytes"] % row["functions"]
                            or bool(row["source"]) != bool(row["matched_functions"])
                            or row["matched_bytes"] * row["functions"]
                            != row["bytes"] * row["matched_functions"]
                            or (row["home"] == SHARED) != (row["modules"] > 1)))
                   for row in table)):
        raise ValueError("shape unit table does not close on the level denominator")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", type=Path, metavar="PINNED_ISO")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        summary, text = measure(args.write)
        UNITS.write_text(text, encoding="utf-8", newline="\n")
        OUTPUT.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8", newline="\n")
    else:
        summary = json.loads(OUTPUT.read_text(encoding="utf-8"))
    check_summary(summary)
    print("accepted level bodies by masked shape: "
          f"{summary['accepted_masked_max_per_module_bytes']} bytes in "
          f"{summary['accepted_masked_max_per_module_units']} shape units; map: "
          f"{summary['map_matched_bytes']} of {summary['map_bytes']} bytes, "
          f"{summary['map_matched_functions']} of {summary['map_functions']} functions")


if __name__ == "__main__":
    main()
