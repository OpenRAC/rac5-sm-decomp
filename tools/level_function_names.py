#!/usr/bin/env python3
"""Evidence-based names for level code: boot twins and original source files.

The level modules keep no names for their own functions: apart from their entry
point they only name the boot functions and data they import. Two kinds of
evidence still name some of their code.

* Boot twins. A candidate level function whose bytes equal, outside its
  relocation fields, the body of exactly one named function of the boot
  executable is a statically linked copy of it and takes that symbol, as
  Quat_Slerp__FP4QUATPC4QUATT1f did. Relocation fields must agree in opcode and,
  for HI16/LO16 fields, in registers. Both bodies must end at their last return
  (`jr $ra` and its delay slot) and be at least 24 bytes long. Calls must agree
  too: a call to a named import must reach the boot function of that name, and a
  call to another level function that is itself a twin must reach that twin's
  boot function. A body that equals several boot functions stays unnamed, and so
  does every copy of a boot function that several functions of one module equal:
  such a shape is too generic to identify a function.
* Original source files. Assertion and debug messages keep source file names
  such as CORE/Breakable.cpp. A candidate interval whose code loads the address
  of such a string belongs to that file, and so does every interval between two
  intervals that cite the same .c/.cpp file, unless another .c/.cpp file is
  cited in between, because a translation unit's code is contiguous. Header
  names only mark the citing interval.

usage: python tools/level_function_names.py --write PINNED_ISO
       python tools/level_function_names.py --check

--write needs the pinned disc and the private candidate worklists and writes
config/levels/function_names.tsv and config/levels/source_files.tsv (offsets,
sizes and names only, no retail bytes). --check verifies that both tables belong
to the current catalogues.
"""

from __future__ import annotations

import argparse
import bisect
import hashlib
import json
import re
import struct
import tempfile
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = ROOT / "config/levels/function_names.tsv"
FILES = ROOT / "config/levels/source_files.tsv"
CODE = ROOT / "config/levels/code_intervals.tsv"
MODULES = ROOT / "config/levels/modules.tsv"
BOOT_INTERVALS = ROOT / "config/boot/code_intervals.tsv"
BOOT_SYMBOLS = ROOT / "config/boot/symbols.tsv"
TARGET = ROOT / "config/target.json"
NAMES_HEADER = ["module", "offset", "size", "symbol", "boot_address"]
FILES_HEADER = ["module", "start", "end", "file", "evidence"]
JR_RA = 0x03E00008
MINIMUM = 24
LEAD_WORDS = 6
FILE_NAME = re.compile(
    rb"(?<![\x21-\x7e])([A-Za-z0-9_][A-Za-z0-9_./-]*\.(?:cpp|c|hpp|h))\x00")


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inputs_note(kind: str) -> str:
    return (f"# Generated by tools/level_function_names.py --write ({kind}). "
            f"code_intervals_sha256: {digest(CODE)} modules_sha256: {digest(MODULES)} "
            f"boot_symbols_sha256: {digest(BOOT_SYMBOLS)}")


def read_table(path: Path) -> tuple[str, list[dict[str, str]]]:
    with path.open(encoding="utf-8", newline="") as file:
        note = file.readline().rstrip()
        header = file.readline().rstrip("\r\n").split("\t")
        rows = [dict(zip(header, line.rstrip("\r\n").split("\t"))) for line in file if line.strip()]
    return note, rows


def tsv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as file:
        lines = [line for line in file if not line.startswith("#")]
    header = lines[0].rstrip("\r\n").split("\t")
    return [dict(zip(header, line.rstrip("\r\n").split("\t"))) for line in lines[1:]]


def body_end(words: tuple[int, ...] | list[int], start: int, end: int) -> int | None:
    """Index after the delay slot of the last `jr $ra` in words[start:end]."""
    for index in range(end - 2, start - 1, -1):
        if words[index] == JR_RA:
            return index + 2
    return None


def skeleton(word: int) -> tuple[int, ...]:
    opcode = word >> 26
    return (opcode, word & 0x3F) if opcode == 0 else (opcode,)


def same_body(level: tuple[int, ...], boot: tuple[int, ...], relocated: dict[int, str]) -> bool:
    """Equal outside relocation fields; relocated words agree in opcode (and registers)."""
    for index, (ours, theirs) in enumerate(zip(level, boot)):
        field = relocated.get(index)
        if field is None:
            if ours != theirs:
                return False
        elif field == "jump":
            if ours >> 26 != theirs >> 26:
                return False
        elif field == "half" and ours >> 16 != theirs >> 16:
            return False
    return True


def jump_target(address: int, word: int) -> int:
    """Target of the J/JAL `word` at `address`."""
    return ((address + 4) & 0xF0000000) | ((word & 0x03FFFFFF) << 2)


def boot_function_names() -> dict[int, str]:
    """Boot .text address -> function symbol (the last label at an address wins)."""
    return {int(row["address"], 16): row["symbol"] for row in tsv(BOOT_SYMBOLS)
            if row["section"] == ".text"}


def boot_bodies(boot_words: tuple[int, ...], text_start: int) -> dict[tuple, list[tuple[str, int, tuple]]]:
    """Named boot bodies indexed by (size, lead skeleton)."""
    index: dict[tuple, list[tuple[str, int, tuple]]] = defaultdict(list)
    for row in tsv(BOOT_INTERVALS):
        start, end = int(row["start"], 16), int(row["end_exclusive"], 16)
        first, last = (start - text_start) // 4, (end - text_start) // 4
        stop = body_end(boot_words, first, last)
        if stop is None or (stop - first) * 4 < MINIMUM:
            continue
        body = tuple(boot_words[first:stop])
        name = row["symbols"].split("|")[-1].strip()
        index[len(body), tuple(skeleton(word) for word in body[:LEAD_WORDS])].append(
            (name, start, body))
    return index


def relocation_fields(indexed: dict[int, tuple]) -> dict[int, str]:
    """Kind of field each relocation site patches: jump target, half word or full word."""
    fields = {}
    for site, (source, kind, _symbol, _addend) in indexed.items():
        if (source == "local" and kind == 2) or (source == "named" and kind == 4):
            fields[site] = "jump"
        elif (source == "local" and kind == 3) or (source == "named" and kind == 2):
            fields[site] = "word"
        else:
            fields[site] = "half"
    return fields


def boot_twins(data: bytes, records: list[tuple[int, int]], indexed: dict[int, tuple],
               index: dict, boot_names: dict[int, str]
               ) -> list[tuple[int, int, str, int, list[tuple[int, str]]]]:
    """Candidate units with one boot twin whose named calls agree.

    Returns (offset, size, symbol, boot address, local calls) where local calls
    are the (level target, boot callee symbol) pairs left for the caller to
    check against the twins of the level targets.
    """
    fields = relocation_fields(indexed)
    out = []
    for offset, size in records:
        if size < MINIMUM or size % 4:
            continue
        words = struct.unpack_from(f"<{size // 4}I", data, offset)
        if words[-2] != JR_RA:
            continue
        candidates = index.get((len(words), tuple(skeleton(word) for word in words[:LEAD_WORDS])), [])
        relocated = {(site - offset) // 4: kind for site, kind in fields.items()
                     if offset <= site < offset + size}
        named = {position: indexed[offset + 4 * position][2]
                 for position, kind in relocated.items()
                 if kind == "jump" and indexed[offset + 4 * position][0] == "named"}
        local = {position: jump_target(offset + 4 * position, words[position])
                 for position, kind in relocated.items()
                 if kind == "jump" and indexed[offset + 4 * position][0] == "local"}
        found = []
        for name, address, body in candidates:
            if not same_body(words, body, relocated):
                continue
            callees = {position: boot_names.get(jump_target(address + 4 * position, body[position]), "")
                       for position in {**named, **local}}
            if all(callees[position] == symbol for position, symbol in named.items()):
                found.append((name, address, [(target, callees[position])
                                              for position, target in sorted(local.items())]))
        if len({name for name, _address, _calls in found}) == 1:
            name, address, calls = found[0]
            out.append((offset, size, name, address, calls))
    return out


def consistent_twins(twins: dict[str, list[tuple[int, int, str, int, list[tuple[int, str]]]]]
                     ) -> dict[str, list[tuple[int, int, str, int]]]:
    """Drop generic shapes and twins whose local calls contradict another twin.

    twins: per module, the boot_twins rows. A symbol that several units of one
    module equal is dropped in every module; a twin whose local call reaches a
    level function named after another boot function than its boot twin calls
    is dropped.
    """
    generic = {symbol for rows in twins.values()
               for symbol, count in Counter(row[2] for row in rows).items() if count > 1}
    out = {}
    for module, rows in twins.items():
        named = {row[0]: row[2] for row in rows if row[2] not in generic}
        out[module] = [(offset, size, symbol, address)
                       for offset, size, symbol, address, calls in rows
                       if symbol not in generic
                       and all(named.get(target, callee) == callee for target, callee in calls)]
    return out


def cited_files(data: bytes, code_end: int, header: tuple) -> dict[str, list[int]]:
    """Code sites (HI16 of a HI16/LO16 pair) that load the address of a source file name."""
    from rel import iter_packed_relocations

    strings = {match.start(1): match.group(1).decode("ascii")
               for match in FILE_NAME.finditer(data, code_end)}
    sites: dict[str, list[int]] = defaultdict(list)
    for relocation in iter_packed_relocations(data, header[13], header[1]):
        if relocation.kind != 1 or relocation.low_site is None or relocation.site >= code_end:
            continue
        high = struct.unpack_from("<I", data, relocation.site)[0] & 0xFFFF
        low = struct.unpack_from("<I", data, relocation.low_site)[0] & 0xFFFF
        address = ((high << 16) + (low - 0x10000 if low & 0x8000 else low)) & 0xFFFFFFFF
        if address in strings:
            sites[strings[address]].append(relocation.site)
    return sites


def attribute_files(static: list[tuple[int, int]],
                    sites: dict[str, list[int]]) -> list[tuple[int, int, str, str]]:
    """(start, end, file, evidence) for each candidate interval tied to a source file."""
    starts = [start for start, _end in static]
    cited: dict[int, set[str]] = defaultdict(set)
    for name, places in sites.items():
        for site in places:
            cited[bisect.bisect_right(starts, site) - 1].add(name)
    owner: dict[int, tuple[str, str]] = {}
    for index, names in cited.items():
        units = {name for name in names if not name.endswith((".h", ".hpp"))}
        if len(units) == 1:
            owner[index] = (units.pop(), "cites")
        elif not units and len(names) == 1:
            owner[index] = (next(iter(names)), "cites")
    by_file: dict[str, list[int]] = defaultdict(list)
    for index, (name, _evidence) in owner.items():
        if not name.endswith((".h", ".hpp")):
            by_file[name].append(index)
    for name, indexes in by_file.items():
        first, last = min(indexes), max(indexes)
        if any(cited.get(index, set()) - {name}
               and any(not other.endswith((".h", ".hpp")) for other in cited[index] - {name})
               for index in range(first, last + 1)):
            continue
        for index in range(first, last + 1):
            owner.setdefault(index, (name, "between"))
    return [(static[index][0], static[index][1], name, evidence)
            for index, (name, evidence) in sorted(owner.items())]


def boot_words_from_disc(disc, target: dict) -> tuple[tuple[int, ...], int]:
    from boot_assembly import TEXT_START, text_words

    with tempfile.TemporaryDirectory() as directory:
        boot = Path(directory) / target["boot_file"]
        boot.write_bytes(disc.file_bytes(target["boot_file"]))
        return text_words(boot, target["boot_sha256"]), TEXT_START


def measure(image: Path) -> tuple[str, str]:
    from disc import IsoDisc, verify_disc
    from level_function_inventory import relocations
    from level_ghidra_crosscheck import rows
    from level_shape_scenario import WORK, measured_unit_records
    from rel import HEADER

    target = json.loads(TARGET.read_text(encoding="utf-8"))
    code = {row["module"]: row for row in rows(CODE)}
    modules = {Path(row["path"]).name: row for row in rows(MODULES)}
    records, _retained, _residual = measured_unit_records(image)
    units: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for module, offset, size, _raw, _masked in records:
        units[module].append((offset, size))
    names, files = [], []
    twins = {}
    boot_names = boot_function_names()
    with IsoDisc(image) as disc:
        verify_disc(disc, target)
        boot_words, text_start = boot_words_from_disc(disc, target)
        index = boot_bodies(boot_words, text_start)
        for module in sorted(units):
            data = disc.file_bytes("LVL/" + module)
            if hashlib.sha256(data).hexdigest() != modules[module]["sha256"]:
                raise ValueError(f"{module} differs from pinned module")
            code_end = int(code[module]["end_exclusive"], 16)
            indexed, _pointers = relocations(data, code_end)
            twins[module] = boot_twins(data, sorted(units[module]), indexed, index, boot_names)
            static = [(int(row["start"], 16), int(row["limit"], 16))
                      for row in rows(WORK / f"{module}.tsv")]
            for start, end, name, evidence in attribute_files(
                    static, cited_files(data, code_end, HEADER.unpack_from(data))):
                files.append(f"{module}\t0x{start:06X}\t0x{end:06X}\t{name}\t{evidence}")
    for module, found in sorted(consistent_twins(twins).items()):
        for offset, size, symbol, address in found:
            names.append(f"{module}\t0x{offset:06X}\t{size}\t{symbol}\t0x{address:08X}")
    names_text = "\n".join([inputs_note("boot twins"), "\t".join(NAMES_HEADER), *names]) + "\n"
    files_text = "\n".join([inputs_note("original source files"), "\t".join(FILES_HEADER),
                            *files]) + "\n"
    return names_text, files_text


def check() -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    """Both tables, verified against the current catalogues."""
    code = {row["module"]: row for row in tsv(CODE)}
    symbols = {(row["symbol"], int(row["address"], 16)) for row in tsv(BOOT_SYMBOLS)
               if row["section"] == ".text"}
    tables = []
    for path, kind, header in ((NAMES, "boot twins", NAMES_HEADER),
                               (FILES, "original source files", FILES_HEADER)):
        note, table = read_table(path)
        if note != inputs_note(kind):
            raise ValueError(f"{path.name} is stale: rerun --write with the pinned disc")
        if any(list(row) != header for row in table):
            raise ValueError(f"{path.name} has an unexpected header")
        tables.append(table)
    names, files = tables
    seen = set()
    for row in names:
        module, offset, size = row["module"], int(row["offset"], 16), int(row["size"])
        if (module not in code or (module, offset) in seen or size < MINIMUM or size % 4
                or not int(code[module]["start"], 16) <= offset < offset + size
                <= int(code[module]["end_exclusive"], 16)
                or (row["symbol"], int(row["boot_address"], 16)) not in symbols):
            raise ValueError(f"function_names.tsv: invalid row {module} {row['offset']}")
        seen.add((module, offset))
    last: dict[str, int] = {}
    for row in files:
        module, start, end = row["module"], int(row["start"], 16), int(row["end"], 16)
        if (module not in code or start >= end or start < last.get(module, 0)
                or row["evidence"] not in ("cites", "between")
                or not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_./-]*\.(?:cpp|c|hpp|h)", row["file"])
                or ".." in row["file"].split("/")):
            raise ValueError(f"source_files.tsv: invalid row {module} {row['start']}")
        last[module] = end
    return names, files


UNIT_FILE = re.compile(r"(?P<folder>[A-Za-z0-9_]+(?:/[A-Za-z0-9_]+)*)\.(?:cpp|c)")


def folder(file: str) -> str:
    """Folder that groups a translation unit's functions: its path without the
    extension. Headers and names that are not plain path components give none."""
    match = UNIT_FILE.fullmatch(file)
    return match.group("folder") if match else ""


def labeller(names: list[dict[str, str]], files: list[dict[str, str]]):
    """labels(module, offset) -> (boot twin symbol, original translation unit)."""
    twins = {(row["module"], int(row["offset"], 16)): row["symbol"] for row in names}
    spans: dict[str, list[tuple[int, int, str]]] = defaultdict(list)
    for row in files:
        if folder(row["file"]):
            spans[row["module"]].append((int(row["start"], 16), int(row["end"], 16), row["file"]))
    starts = {module: [start for start, _end, _file in items] for module, items in spans.items()}

    def labels(module: str, offset: int) -> tuple[str, str]:
        items = spans.get(module, [])
        index = bisect.bisect_right(starts.get(module, []), offset) - 1
        file = items[index][2] if index >= 0 and offset < items[index][1] else ""
        return twins.get((module, offset), ""), file

    return labels


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", type=Path, metavar="PINNED_ISO")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        names_text, files_text = measure(args.write)
        NAMES.write_text(names_text, encoding="utf-8", newline="\n")
        FILES.write_text(files_text, encoding="utf-8", newline="\n")
    names, files = check()
    print(f"level function names: {len(names)} boot-twin placements "
          f"({len({row['symbol'] for row in names})} boot symbols); "
          f"{len(files)} intervals in {len({row['file'] for row in files})} original source files")


if __name__ == "__main__":
    main()
