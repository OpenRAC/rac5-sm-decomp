#!/usr/bin/env python3
"""Record the zero alignment padding in the boot .text.

Every candidate boot code interval (config/boot/code_intervals.tsv) runs to the
next label, so it may end with zero words that the linker inserted to align the
next function; zero words also precede the first interval. A zero word that is
the delay slot of a final branch or jump is code, not padding. --write measures
the padding in the pinned boot ELF and writes config/boot/zero_padding.tsv
(addresses and sizes only, no retail bytes). The progress report leaves this
padding out of the boot code it counts; the measured .text size is unchanged.

usage: python tools/boot_zero_padding.py --write PINNED_BOOT_ELF
       python tools/boot_zero_padding.py --check

--check verifies that the table belongs to the current interval catalogue and
agrees with the verified witness boundaries (config/boot/witness_boundaries.tsv).
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import struct
from pathlib import Path

from boot_assembly import ROOT, TEXT_SIZE, TEXT_START, text_words
from boot_promotion_audit import catalogue_rows
from zero_padding import trailing_zero_padding

INTERVALS = ROOT / "config/boot/code_intervals.tsv"
OUTPUT = ROOT / "config/boot/zero_padding.tsv"
TARGET = ROOT / "config/target.json"
HEADER = ["start", "zero_padding_bytes"]
NOTE = ("# Generated by tools/boot_zero_padding.py --write: trailing zero alignment words "
        "of each candidate boot code interval, and the zero words before the first one. "
        "code_intervals_sha256: ")


def intervals() -> list[tuple[int, int]]:
    with INTERVALS.open(encoding="utf-8", newline="") as file:
        rows = csv.DictReader((line for line in file if not line.startswith("#")),
                              delimiter="\t")
        return [(int(row["start"], 16), int(row["end_exclusive"], 16)) for row in rows]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def measure(boot: Path) -> dict[int, int]:
    target = json.loads(TARGET.read_text(encoding="utf-8"))
    words = text_words(boot, target["boot_sha256"])
    text = struct.pack(f"<{len(words)}I", *words)
    spans = intervals()
    first = spans[0][0]
    padding: dict[int, int] = {}
    if first > TEXT_START:
        if any(text[:first - TEXT_START]):
            raise ValueError("the bytes before the first boot interval are not zero")
        padding[TEXT_START] = first - TEXT_START
    for start, end in spans:
        size = trailing_zero_padding(text, start - TEXT_START, end - TEXT_START)
        if size:
            padding[start] = size
    return padding


def render(padding: dict[int, int]) -> str:
    lines = [NOTE + digest(INTERVALS), "\t".join(HEADER)]
    lines.extend(f"0x{start:08X}\t{size}" for start, size in sorted(padding.items()))
    return "\n".join(lines) + "\n"


def read() -> dict[int, int]:
    """The committed padding, checked against the current catalogues."""
    with OUTPUT.open(encoding="utf-8", newline="") as file:
        note = file.readline().rstrip()
        rows = list(csv.DictReader(file, delimiter="\t"))
    if not note.startswith(NOTE) or note[len(NOTE):] != digest(INTERVALS):
        raise ValueError("boot zero padding table is stale: rerun --write")
    padding = {int(row["start"], 16): int(row["zero_padding_bytes"]) for row in rows}
    spans = intervals()
    ends = dict(spans)
    first = spans[0][0]
    for start, size in padding.items():
        limit = first - TEXT_START if start == TEXT_START else ends.get(start, start) - start
        if (size <= 0 or size % 4 or size > limit
                or (start == TEXT_START) != (start not in ends)
                or (start == TEXT_START and size != limit)):
            raise ValueError(f"boot zero padding row 0x{start:08X} is invalid")
    for row in catalogue_rows():
        if (ends.get(row["start"]) == row["next_label"]
                and padding.get(row["start"], 0) != row["zero_padding_bytes"]):
            raise ValueError(f"boot zero padding disagrees with the witness boundary "
                             f"0x{row['start']:08X}")
    if sum(padding.values()) >= TEXT_SIZE:
        raise ValueError("boot zero padding exceeds the boot .text")
    return padding


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", type=Path, metavar="PINNED_BOOT_ELF")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        OUTPUT.write_text(render(measure(args.write)), encoding="utf-8", newline="\n")
    padding = read()
    print(f"boot zero padding: {sum(padding.values())} bytes in {len(padding)} places "
          f"of the {TEXT_SIZE}-byte .text")


if __name__ == "__main__":
    main()
