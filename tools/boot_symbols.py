#!/usr/bin/env python3
"""Read metadata names/addresses from the boot ELF's embedded SNR2 table.

Symbols are not function boundaries or byte matches. The boot's .sndata SNR2
table uses linked virtual addresses, unlike the level modules' file offsets.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from elf import inspect_elf
from rel import HEADER, MAGIC, RELOCATION, SYMBOL, unpack_relocation

ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class BootSymbol:
    name: str
    address: int
    kind: int
    section: str


def parse_sndata(data: bytes, base: int, sections: list[dict[str, object]]) -> list[BootSymbol]:
    if len(data) < HEADER.size:
        raise ValueError("short .sndata SNR2 header")
    head = HEADER.unpack_from(data)
    if head[0] != MAGIC:
        raise ValueError(".sndata has no SNR2 header")
    declared_size = head[11]
    reloc_at, symbol_at = head[1] - base, head[3] - base
    if (declared_size > len(data) or reloc_at < HEADER.size
            or reloc_at + head[2] * RELOCATION.size != symbol_at
            or symbol_at + head[4] * SYMBOL.size > declared_size):
        raise ValueError("invalid .sndata SNR2 table bounds")

    for index in range(head[2]):
        _offset, _kind, symbol, _addend = unpack_relocation(
            data, reloc_at + index * RELOCATION.size)
        if symbol >= head[4]:
            raise ValueError(f"invalid .sndata relocation symbol {index}")

    ranges = []
    for section in sections:
        if section["flags"] & 2 and section["size"]:
            start = int(str(section["virtual_address"]), 16)
            ranges.append((start, start + section["size"], str(section["name"])))
    symbols: list[BootSymbol] = []
    for index in range(head[4]):
        name_address, address, _aux, kind, _flags = SYMBOL.unpack_from(
            data, symbol_at + index * SYMBOL.size)
        name_at = name_address - base
        if name_at < HEADER.size or name_at >= reloc_at:
            raise ValueError(f"invalid .sndata symbol name {index}")
        end = data.find(b"\0", name_at, min(reloc_at, name_at + 256))
        if end < 0:
            raise ValueError(f"unterminated .sndata symbol name {index}")
        name = data[name_at:end].decode("ascii", "strict")
        if not name:
            continue
        zone = "unresolved" if address == 0 else next(
            (label for start, stop, label in ranges if start <= address < stop), "outside")
        symbols.append(BootSymbol(name, address, kind, zone))
    return symbols


def read_boot(path: Path) -> tuple[dict[str, object], list[BootSymbol]]:
    report = inspect_elf(path)
    section = next((s for s in report["sections"] if s["name"] == ".sndata"), None)
    if section is None:
        raise ValueError("boot ELF has no .sndata section")
    image = path.read_bytes()
    offset = int(section["file_offset"])
    data = image[offset:offset + int(section["size"])]
    base = int(str(section["virtual_address"]), 16)
    symbols = parse_sndata(data, base, report["sections"])
    reginfo = next((s for s in report["sections"] if s["name"] == ".reginfo"), None)
    gp = next((s.address for s in symbols if s.name == "_gp"), None)
    if reginfo is not None and reginfo["size"] == 24 and gp is not None:
        import struct
        recorded_gp = struct.unpack_from("<I", image, int(reginfo["file_offset"]) + 20)[0]
        if gp != recorded_gp:
            raise ValueError("_gp symbol disagrees with ELF .reginfo")
    return report, symbols


def render_symbols(symbols: list[BootSymbol]) -> str:
    lines = ["# Generated by tools/boot_symbols.py; symbols are facts, not matched functions.",
             "symbol\taddress\tkind\tsection"]
    for symbol in sorted(symbols, key=lambda item: (item.address, item.name)):
        lines.append(f"{symbol.name}\t0x{symbol.address:08X}\t{symbol.kind}\t{symbol.section}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("inspect", "catalogue"))
    parser.add_argument("boot", type=Path)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    report, symbols = read_boot(args.boot)
    if args.command == "catalogue":
        target = json.loads((ROOT / "config/target.json").read_text(encoding="utf-8"))
        if report["sha256"] != target["boot_sha256"] or report["file_size"] != target["boot_size"]:
            raise ValueError("boot ELF differs from the pinned USA target")
        path = ROOT / "config/boot/symbols.tsv"
        content = render_symbols(symbols)
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise ValueError("config/boot/symbols.tsv is missing or stale; run catalogue --write")
    counts = Counter(symbol.section for symbol in symbols)
    print(f"boot .sndata: {len(symbols)} named symbols, "
          + ", ".join(f"{zone}={count}" for zone, count in sorted(counts.items())))


if __name__ == "__main__":
    main()
